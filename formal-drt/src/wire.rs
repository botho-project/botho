//! The JSON wire format shared with the Lean executable
//! (`formal-drt/lean/Drt/Codec.lean`): every integer is a decimal string,
//! every byte string lowercase hex, `Option` is `null` or the value.

use serde::{Deserialize, Deserializer, Serializer};
use serde_json::{json, Value};

/// An integer as a decimal string.
pub fn n(x: impl ToString) -> Value {
    Value::String(x.to_string())
}

/// A byte string as lowercase hex.
pub fn b(bytes: &[u8]) -> Value {
    Value::String(hex::encode(bytes))
}

/// A list of values.
pub fn list<T>(items: &[T], f: impl Fn(&T) -> Value) -> Value {
    Value::Array(items.iter().map(f).collect())
}

/// A `{"fn": name, "args": args}` request line.
pub fn request(name: &str, args: &Value) -> String {
    json!({ "fn": name, "args": args }).to_string()
}

/// Serde helper: `Vec<u8>` as a hex string in fixture files.
pub mod hex_bytes {
    use super::*;

    pub fn serialize<S: Serializer>(v: &[u8], s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(&hex::encode(v))
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(d: D) -> Result<Vec<u8>, D::Error> {
        let s = String::deserialize(d)?;
        hex::decode(s).map_err(serde::de::Error::custom)
    }
}

/// Serde helper: `u128` as a decimal string in fixture files (JSON numbers
/// above 2^53 do not survive every reader).
pub mod dec_u128 {
    use super::*;

    pub fn serialize<S: Serializer>(v: &u128, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(&v.to_string())
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(d: D) -> Result<u128, D::Error> {
        String::deserialize(d)?
            .parse()
            .map_err(serde::de::Error::custom)
    }
}

/// A fixed-size array from a generated byte vector.
pub fn arr<const N: usize>(v: &[u8]) -> [u8; N] {
    v.try_into()
        .expect("generator produced a byte string of the wrong length")
}
